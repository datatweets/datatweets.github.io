def random_date(start: dt.date, span_days: int) -> dt.date:
    return start + dt.timedelta(days=int(rng.integers(0, span_days)))


# ---------------------------------------------------------------------------
# 1. Customers
# ---------------------------------------------------------------------------

def build_customers() -> pl.DataFrame:
    rows = []
    signup_start = dt.date(2022, 1, 1)
    signup_span = (dt.date(2025, 12, 31) - signup_start).days + 1
    for i in range(1, N_CUSTOMERS + 1):
        first = rng.choice(FIRST_NAMES)
        last = rng.choice(LAST_NAMES)
        city, state = CITY_STATE[rng.integers(0, len(CITY_STATE))]
        segment = rng.choice(["retail", "wholesale"], p=[0.85, 0.15])
        email = f"{first.lower()}.{last.lower()}{i:03d}@thistlewoodmail.example"
        rows.append(
            {
                "customer_id": f"C{i:04d}",
                "first_name": first,
                "last_name": last,
                "email": email,
                "city": city,
                "state": state,
                "signup_date": random_date(signup_start, signup_span).isoformat(),
                "segment": segment,
            }
        )
    return pl.DataFrame(rows)


# ---------------------------------------------------------------------------
# 2. Products
# ---------------------------------------------------------------------------

def build_products() -> pl.DataFrame:
    categories = list(CATEGORY_TREE.keys())
    base, extra = divmod(N_PRODUCTS, len(categories))
    per_category = [base + (1 if i < extra else 0) for i in range(len(categories))]

    rows = []
    used_names = set()
    pid = 1
    for category, count in zip(categories, per_category):
        subcats = list(CATEGORY_TREE[category].keys())
        for _ in range(count):
            subcategory = rng.choice(subcats)
            nouns = CATEGORY_TREE[category][subcategory]
            noun = rng.choice(nouns)
            for _attempt in range(20):
                adjective = rng.choice(ADJECTIVES)
                name = f"{adjective} {noun}"
                if name not in used_names:
                    used_names.add(name)
                    break
            unit_price = round(float(rng.uniform(8, 450)), 2)
            cost_ratio = float(rng.uniform(0.60, 0.75))
            cost = round(unit_price * cost_ratio, 2)
            supplier = rng.choice(SUPPLIERS)
            rows.append(
                {
                    "product_id": f"P{pid:03d}",
                    "product_name": name,
                    "category": category,
                    "subcategory": subcategory,
                    "unit_price": unit_price,
                    "cost": cost,
                    "supplier": supplier,
                }
            )
            pid += 1
    return pl.DataFrame(rows)


# ---------------------------------------------------------------------------
# 3. Orders
# ---------------------------------------------------------------------------

def build_orders(customer_ids: list) -> pl.DataFrame:
    rows = []
    for i in range(1, N_ORDERS + 1):
        order_date = random_date(ORDER_START, ORDER_SPAN_DAYS)
        rows.append(
            {
                "order_id": f"O{i:05d}",
                "order_date": order_date.isoformat(),
                "customer_id": rng.choice(customer_ids),
                "channel": rng.choice(CHANNELS, p=CHANNEL_P),
                "status": rng.choice(STATUSES, p=STATUS_P),
            }
        )
    return pl.DataFrame(rows).sort("order_date")


# ---------------------------------------------------------------------------
# 4. Promotions (generated before order_items so line-item prices can
#    reflect an active promotion discount)
# ---------------------------------------------------------------------------

def build_promotions(categories: list, product_ids: list) -> pl.DataFrame:
    rows = []
    n_category_promos = 15
    n_product_promos = N_PROMOTIONS - n_category_promos
    for i in range(1, N_PROMOTIONS + 1):
        duration = int(rng.integers(14, 29))  # 2-4 weeks
        latest_start = ORDER_SPAN_DAYS - duration - 1
        start = random_date(ORDER_START, max(latest_start, 1))
        end = start + dt.timedelta(days=duration)
        discount_pct = int(rng.integers(10, 31))
        if i <= n_category_promos:
            category = rng.choice(categories)
            product_id = None
        else:
            category = None
            product_id = rng.choice(product_ids)
        rows.append(
            {
                "promo_code": f"PROMO{i:02d}",
                "category": category,
                "product_id": product_id,
                "discount_pct": discount_pct,
                "start_date": start.isoformat(),
                "end_date": end.isoformat(),
            }
        )
    return pl.DataFrame(
        rows,
        schema={
            "promo_code": pl.Utf8,
            "category": pl.Utf8,
            "product_id": pl.Utf8,
            "discount_pct": pl.Int64,
            "start_date": pl.Utf8,
            "end_date": pl.Utf8,
        },
    )


def active_discount(promos: list, category: str, product_id: str, order_date: dt.date) -> float:
    """Best (highest) discount pct active for this line item on this date, or 0."""
    best = 0
    for p in promos:
        start = dt.date.fromisoformat(p["start_date"])
        end = dt.date.fromisoformat(p["end_date"])
        if not (start <= order_date <= end):
            continue
        if p["product_id"] == product_id or p["category"] == category:
            best = max(best, p["discount_pct"])
    return best


# ---------------------------------------------------------------------------
# 5. Order items
# ---------------------------------------------------------------------------

ITEM_COUNT_CHOICES = [1, 2, 3, 4]
ITEM_COUNT_P = [0.25, 0.30, 0.30, 0.15]


def build_order_items(orders: list, products_by_id: dict, product_ids: list, promos: list) -> list:
    rows = []
    item_id = 1
    for order in orders:
        n_items = rng.choice(ITEM_COUNT_CHOICES, p=ITEM_COUNT_P)
        chosen_products = rng.choice(product_ids, size=n_items, replace=False)
        order_date = dt.date.fromisoformat(order["order_date"])
        for product_id in chosen_products:
            product = products_by_id[product_id]
            quantity = int(rng.integers(1, 6))
            discount = active_discount(promos, product["category"], product_id, order_date)
            unit_price_at_sale = round(product["unit_price"] * (1 - discount / 100), 2)
            rows.append(
                {
                    "order_item_id": f"OI{item_id:05d}",
                    "order_id": order["order_id"],
                    "product_id": product_id,
                    "quantity": quantity,
                    "unit_price_at_sale": unit_price_at_sale,
                }
            )
            item_id += 1
    return rows


# ---------------------------------------------------------------------------
# 6. Returns
# ---------------------------------------------------------------------------

def build_returns(orders: list, order_items_by_order: dict) -> pl.DataFrame:
    completed_orders = [o for o in orders if o["status"] == "completed"]
    n_returns = round(N_ORDERS * RETURN_RATE)
    chosen_idx = rng.choice(len(completed_orders), size=n_returns, replace=False)
    rows = []
    for i, idx in enumerate(sorted(chosen_idx), start=1):
        order = completed_orders[idx]
        items = order_items_by_order[order["order_id"]]
        item = items[int(rng.integers(0, len(items)))]
        order_date = dt.date.fromisoformat(order["order_date"])
        return_date = order_date + dt.timedelta(days=int(rng.integers(3, 31)))
        return_qty = int(rng.integers(1, item["quantity"] + 1))
        rows.append(
            {
                "return_id": f"R{i:05d}",
                "order_id": order["order_id"],
                "product_id": item["product_id"],
                "return_date": return_date.isoformat(),
                "reason": rng.choice(RETURN_REASONS),
                "quantity": return_qty,
            }
        )
    return pl.DataFrame(rows)


# ---------------------------------------------------------------------------
# 7. Flat, already-joined Lesson-1 file (Q1 2024 only)
# ---------------------------------------------------------------------------

def build_orders_flat(customers: pl.DataFrame, products: pl.DataFrame,
                       orders: pl.DataFrame, order_items: pl.DataFrame) -> pl.DataFrame:
    q1_orders = orders.filter(
        (pl.col("order_date") >= "2024-01-01")
        & (pl.col("order_date") <= "2024-03-31")
        & (pl.col("status") == "completed")
    )
    flat = (
        q1_orders.join(order_items, on="order_id", how="inner")
        .join(products, on="product_id", how="inner")
        .join(customers, on="customer_id", how="inner")
        .with_columns(
            (pl.col("first_name") + " " + pl.col("last_name")).alias("customer_name"),
            (pl.col("quantity") * pl.col("unit_price_at_sale")).round(2).alias("total"),
        )
        .select(
            "order_id",
            "order_date",
            "customer_name",
            pl.col("product_name"),
            "category",
            "quantity",
            pl.col("unit_price_at_sale").alias("unit_price"),
            "total",
        )
        .sort(["order_date", "order_id"])
    )
    return flat


# ---------------------------------------------------------------------------
# Build everything and write CSVs
# ---------------------------------------------------------------------------

def main():
    customers = build_customers()
    products = build_products()

    customer_ids = customers["customer_id"].to_list()
    product_ids = products["product_id"].to_list()
    categories = products["category"].unique().to_list()
    products_by_id = {row["product_id"]: row for row in products.to_dicts()}

    orders_df = build_orders(customer_ids)
    orders_list = orders_df.to_dicts()

    promotions_df = build_promotions(categories, product_ids)
    promos_list = promotions_df.to_dicts()

    order_items_rows = build_order_items(orders_list, products_by_id, product_ids, promos_list)
    order_items_df = pl.DataFrame(order_items_rows)

    order_items_by_order: dict = {}
    for row in order_items_rows:
        order_items_by_order.setdefault(row["order_id"], []).append(row)

    returns_df = build_returns(orders_list, order_items_by_order)

    orders_flat_df = build_orders_flat(customers, products, orders_df, order_items_df)

    files = {
        "thistlewood_customers.csv": customers,
        "thistlewood_products.csv": products,
        "thistlewood_orders.csv": orders_df,
        "thistlewood_order_items.csv": order_items_df,
        "thistlewood_returns.csv": returns_df,
        "thistlewood_promotions.csv": promotions_df,
        "thistlewood_orders_flat.csv": orders_flat_df,
    }
    for filename, df in files.items():
        path = os.path.join(OUT_DIR, filename)
        df.write_csv(path)
        print(f"wrote {filename:32s} {df.height:>7,} rows  {df.width} cols")


if __name__ == "__main__":
    main()
